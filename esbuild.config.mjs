import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

// Helper plugin to copy and patch onnxruntime-web WASM & MJS binaries to output directories
const copyWasmPlugin = {
	name: "copy-wasm-plugin",
	setup(build) {
		build.onEnd(() => {
			try {
				const ortDistPath = path.resolve("node_modules/onnxruntime-web/dist");
				if (fs.existsSync(ortDistPath)) {
					const files = fs.readdirSync(ortDistPath);
					const targets = [path.resolve("."), path.resolve("v0")];
					for (const targetDir of targets) {
						if (!fs.existsSync(targetDir)) {
							fs.mkdirSync(targetDir, { recursive: true });
						}
					}

					for (const file of files) {
						if (file.endsWith(".wasm")) {
							const src = path.join(ortDistPath, file);
							for (const targetDir of targets) {
								fs.copyFileSync(src, path.join(targetDir, file));
							}
						} else if (file.endsWith(".mjs")) {
							let content = fs.readFileSync(path.join(ortDistPath, file), "utf8");
							// 1. Sanitize node-only imports that cause browser ES module syntax errors in Electron
							content = content.replace(/await\s+import\s*\(\s*["']module["']\s*\)/g, "{ createRequire: () => () => ({}) }");
							content = content.replace(/await\s+import\s*\(\s*["']worker_threads["']\s*\)/g, "{ workerData: undefined }");
							content = content.replace(/require\s*\(\s*["']worker_threads["']\s*\)/g, "{}");

							// 2. Intercept WASM binary fetch to load directly from local filesystem in Electron
							const wasmFetchPattern = /var\s+b\s*=\s*await\s+fetch\s*\(\s*a\s*,\s*\{\s*credentials:\s*"same-origin"\s*\}\s*\);\s*if\s*\(\s*b\.ok\s*\)\s*return\s+b\.arrayBuffer\(\);/g;
							const wasmFsReplacement = `if (typeof require === "function" && typeof a === "string" && a.startsWith("file://")) {
								const fs = require("fs");
								const p = decodeURIComponent(a.replace(/^file:\\/\\//, ""));
								if (fs.existsSync(p)) {
									const buf = fs.readFileSync(p);
									return buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
								}
							}
							var b = await fetch(a, { credentials: "same-origin" });
							if (b.ok) return b.arrayBuffer();`;
							content = content.replace(wasmFetchPattern, wasmFsReplacement);

							// 3. Patch Emscripten's async la(a) and sync ma(a) file loaders that trigger blocked XMLHttpRequest on file:// URIs
							const xhrAsyncPattern = /if\(na\(a\)\)return new Promise\(\(d,c\)=>\{var e=new XMLHttpRequest;e\.open\("GET",a,!0\);e\.responseType="arraybuffer";e\.onload=\(\)=>\{200==e\.status\|\|0==e\.status&&e\.response\?d\(e\.response\):c\(e\.status\)\};e\.onerror=c;e\.send\(null\)\}\);/g;
							const fsAsyncReplacement = `if (typeof require === "function" && typeof a === "string" && a.startsWith("file://")) {
								const fs = require("fs");
								const p = decodeURIComponent(a.replace(/^file:\\/\\//, ""));
								if (fs.existsSync(p)) {
									const buf = fs.readFileSync(p);
									return buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
								}
							}`;
							content = content.replace(xhrAsyncPattern, fsAsyncReplacement);

							const xhrSyncPattern = /ba&&\(ma=a=>\{var b=new XMLHttpRequest;b\.open\("GET",a,!1\);b\.responseType="arraybuffer";\s*b\.send\(null\);return new Uint8Array\(b\.response\)\}\)/g;
							const fsSyncReplacement = `ma = a => {
								if (typeof require === "function" && typeof a === "string" && a.startsWith("file://")) {
									const fs = require("fs");
									const p = decodeURIComponent(a.replace(/^file:\\/\\//, ""));
									if (fs.existsSync(p)) {
										const buf = fs.readFileSync(p);
										return new Uint8Array(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
									}
								}
								if (ba) {
									var b = new XMLHttpRequest; b.open("GET", a, false); b.responseType = "arraybuffer"; b.send(null); return new Uint8Array(b.response);
								}
							}`;
							// 4. Directly patch Ta(a) which resolves wasm binary Uint8Array
							const taPattern = /async function Ta\(a\)\{if\(!ta\)try\{var b=await la\(a\);return new Uint8Array\(b\)\}catch\{\}if\(a==Sa&&ta\)a=new Uint8Array\(ta\);else if\(ma\)a=ma\(a\);else throw"both async and sync fetching of the wasm failed";return a\}/g;
							const taReplacement = `async function Ta(a) {
								if (typeof require === "function" && typeof a === "string" && a.startsWith("file://")) {
									const fs = require("fs");
									const p = decodeURIComponent(a.replace(/^file:\\/\\//, ""));
									if (fs.existsSync(p)) {
										const buf = fs.readFileSync(p);
										return new Uint8Array(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
									}
								}
								if (!ta) try { var b = await la(a); return new Uint8Array(b); } catch {}
								if (a == Sa && ta) a = new Uint8Array(ta);
								else if (ma) a = ma(a);
								else throw "both async and sync fetching of the wasm failed";
								return a;
							}`;
							content = content.replace(taPattern, taReplacement);

							for (const targetDir of targets) {
								fs.writeFileSync(path.join(targetDir, file), content, "utf8");
							}
						}
					}
					console.log("[copy-wasm-plugin] onnxruntime-web .wasm and .mjs files copied and sanitized successfully.");
				}

				// Post-process main.js to intercept dynamic import(r) for file:// URLs
				const mainJsPath = path.resolve("main.js");
				if (fs.existsSync(mainJsPath)) {
					let mainJs = fs.readFileSync(mainJsPath, "utf8");
					// Replace (await import(r)).default with safe Blob URL dynamic importer
					const search = `(await import(r)).default`;
					const replacement = `(await (async (specifier) => {
						if (typeof require === "function" && typeof specifier === "string" && specifier.startsWith("file://")) {
							const fs = require("fs");
							const filePath = decodeURIComponent(specifier.replace(/^file:\\/\\//, ""));
							if (fs.existsSync(filePath)) {
								const fileContent = fs.readFileSync(filePath, "utf8");
								const blob = new Blob([fileContent], { type: "text/javascript" });
								return import(URL.createObjectURL(blob));
							}
						}
						return import(specifier);
					})(r)).default`;

					if (mainJs.includes(search)) {
						mainJs = mainJs.replaceAll(search, replacement);
						fs.writeFileSync(mainJsPath, mainJs, "utf8");
						console.log("[copy-wasm-plugin] main.js dynamic import successfully patched with Blob URL loader.");
					}
				}

				// Also sync main.js, manifest.json, styles.css to v0
				const v0Dir = path.resolve("v0");
				if (fs.existsSync(v0Dir)) {
					for (const syncFile of ["main.js", "manifest.json", "styles.css"]) {
						if (fs.existsSync(path.resolve(syncFile))) {
							fs.copyFileSync(path.resolve(syncFile), path.join(v0Dir, syncFile));
						}
					}
				}

				// Automatically sync to live vault if present
				const vaultPluginPaths = [
					"/Users/rahulrajeev/Downloads/lattice field/.obsidian/plugins/v0",
					"/Users/rahulrajeev/Downloads/lattice field/.obsidian/plugins/lets-hear-it"
				];
				for (const vaultDir of vaultPluginPaths) {
					if (fs.existsSync(vaultDir)) {
						const v0Files = fs.readdirSync(v0Dir);
						for (const f of v0Files) {
							fs.copyFileSync(path.join(v0Dir, f), path.join(vaultDir, f));
						}
						console.log(`[copy-wasm-plugin] Synced all files to live vault: ${vaultDir}`);
					}
				}
			} catch (err) {
				console.warn("[copy-wasm-plugin] Warning copying files:", err);
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	define: {
		"process.release.name": '"browser"',
	},
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [copyWasmPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
